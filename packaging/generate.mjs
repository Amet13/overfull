#!/usr/bin/env node
// Writes the package manifests of one release from that release's SHA256SUMS:
//   - a Homebrew formula (overfull.rb, in the repository as Formula/overfull.rb),
//   - a Scoop manifest (overfull.json, in the repository as bucket/overfull.json),
//   - a Nix flake (flake.nix, repository only),
//   - the MCP Registry entry (server.json, repository only; no checksums needed).
// This repository is itself the Homebrew tap, the Scoop bucket and the flake. The release
// workflow attaches overfull.rb and overfull.json to the release (--out) and opens an
// automation pull request with the repository files (--repo). See packaging/README.md.
//
//   node packaging/generate.mjs --version 3.1.0 --sums assets/SHA256SUMS --out assets
//   node packaging/generate.mjs --version 3.1.0 --sums SHA256SUMS --repo .
//
// No dependencies, so it runs on a bare runner.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseArgs } from 'node:util';

export const REPO = 'amet13/overfull';
/**
 * The MCP Registry name. GitHub sign-in grants `io.github.<owner>/*` with the owner's
 * login spelled exactly as GitHub spells it (Amet13), and the registry compares names
 * case-sensitively.
 */
export const MCP_NAME = 'io.github.Amet13/overfull';
const DESC = 'Preflight checks for LaTeX papers and theses';
const HOMEPAGE = 'https://amet13.github.io/overfull/';
const IMAGE = 'ghcr.io/amet13/overfull';

/** `<sha256>  <file>` lines → Map(file → sha256). Rejects anything that is not a checksum line. */
export function parseSums(text) {
  const sums = new Map();
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    const m = /^([0-9a-f]{64}) [ *]?(\S+)$/.exec(line.trim());
    if (!m) throw new Error(`not a SHA256SUMS line: ${line.slice(0, 80)}`);
    sums.set(m[2], m[1]);
  }
  return sums;
}

function checkVersion(version) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`not a version: ${version}`);
}

function need(sums, file) {
  const sum = sums.get(file);
  if (!sum) throw new Error(`SHA256SUMS has no entry for ${file}`);
  return sum;
}

export function formula(version, sums) {
  checkVersion(version);
  const url = (f) => `https://github.com/${REPO}/releases/download/v${version}/${f}`;
  const block = (f) => [`      url "${url(f)}"`, `      sha256 "${need(sums, f)}"`].join('\n');
  return `# Generated by packaging/generate.mjs for Overfull v${version}. Do not edit by hand.
class Overfull < Formula
  desc "${DESC}"
  homepage "${HOMEPAGE}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block('overfull-darwin-arm64')}
    end
    on_intel do
${block('overfull-darwin-x64')}
    end
  end

  on_linux do
    on_arm do
${block('overfull-linux-arm64')}
    end
    on_intel do
${block('overfull-linux-x64')}
    end
  end

  def install
    bin.install Dir["overfull-*"].first => "overfull"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/overfull --version")
  end
end
`;
}

export function scoop(version, sums) {
  checkVersion(version);
  const base = `https://github.com/${REPO}/releases/download`;
  return `${JSON.stringify(
    {
      '##': `Generated by packaging/generate.mjs for Overfull v${version}. Do not edit by hand.`,
      version,
      description: DESC,
      homepage: HOMEPAGE,
      license: 'MIT',
      architecture: {
        '64bit': {
          url: `${base}/v${version}/overfull-win-x64.exe#/overfull.exe`,
          hash: need(sums, 'overfull-win-x64.exe'),
        },
      },
      bin: 'overfull.exe',
      checkver: { github: `https://github.com/${REPO}` },
      autoupdate: {
        architecture: {
          '64bit': { url: `${base}/v$version/overfull-win-x64.exe#/overfull.exe` },
        },
        hash: { url: '$baseurl/SHA256SUMS' },
      },
    },
    null,
    2,
  )}\n`;
}

/** A SHA-256 in hex as the SRI string Nix wants (`sha256-<base64>`). */
export function sri(hex) {
  return `sha256-${Buffer.from(hex, 'hex').toString('base64')}`;
}

/** Nix system → release executable. */
const NIX_SYSTEMS = [
  ['x86_64-linux', 'overfull-linux-x64'],
  ['aarch64-linux', 'overfull-linux-arm64'],
  ['x86_64-darwin', 'overfull-darwin-x64'],
  ['aarch64-darwin', 'overfull-darwin-arm64'],
];

/**
 * A flake with one package per system: the release executable, gzip copy when the release
 * has one (a third of the download). On Linux, autoPatchelfHook points it at Nix's own C
 * library. Never stripped: the CLI is embedded in the executable.
 */
export function flake(version, sums) {
  checkVersion(version);
  const assets = NIX_SYSTEMS.map(([system, exe]) => {
    const file = sums.has(`${exe}.gz`) ? `${exe}.gz` : exe;
    return `        ${system} = {\n          file = "${file}";\n          hash = "${sri(need(sums, file))}";\n        };`;
  }).join('\n');
  return `# Generated by packaging/generate.mjs for Overfull v${version}. Do not edit by hand.
#   nix run github:Amet13/overfull -- --version
#   nix profile install github:Amet13/overfull
{
  description = "${DESC}";

  inputs.nixpkgs.url = "github:NixOS/nixpkgs/nixos-unstable";

  outputs =
    { self, nixpkgs }:
    let
      version = "${version}";
      assets = {
${assets}
      };
      forAllSystems = nixpkgs.lib.genAttrs (builtins.attrNames assets);
    in
    {
      packages = forAllSystems (
        system:
        let
          pkgs = nixpkgs.legacyPackages.\${system};
          asset = assets.\${system};
          gz = pkgs.lib.hasSuffix ".gz" asset.file;
        in
        {
          overfull = pkgs.stdenv.mkDerivation {
            pname = "overfull";
            inherit version;
            src = pkgs.fetchurl {
              url = "https://github.com/${REPO}/releases/download/v\${version}/\${asset.file}";
              inherit (asset) hash;
            };
            dontUnpack = true;
            dontStrip = true;
            nativeBuildInputs = pkgs.lib.optionals pkgs.stdenv.hostPlatform.isLinux [
              pkgs.autoPatchelfHook
            ];
            buildInputs = pkgs.lib.optionals pkgs.stdenv.hostPlatform.isLinux [ pkgs.stdenv.cc.cc.lib ];
            installPhase = ''
              runHook preInstall
              mkdir -p $out/bin
              \${if gz then "gzip -dc $src" else "cat $src"} > $out/bin/overfull
              chmod 755 $out/bin/overfull
              runHook postInstall
            '';
            meta = {
              description = "${DESC}";
              homepage = "${HOMEPAGE}";
              license = pkgs.lib.licenses.mit;
              mainProgram = "overfull";
              platforms = [ system ];
              sourceProvenance = [ pkgs.lib.sourceTypes.binaryNativeCode ];
            };
          };
          default = self.packages.\${system}.overfull;
        }
      );
    };
}
`;
}

/**
 * The MCP Registry entry: the check-only image of this version, started with the
 * project folder mounted at /work, running `overfull mcp`. The registry checks that
 * the image carries the label `io.modelcontextprotocol.server.name` = MCP_NAME.
 */
export function serverJson(version) {
  checkVersion(version);
  return `${JSON.stringify(
    {
      $schema: 'https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json',
      name: MCP_NAME,
      title: 'Overfull',
      description:
        'LaTeX preflight: build log, PDF, references, PDF/UA and venue rules, with rule ids and fixes',
      version,
      websiteUrl: HOMEPAGE,
      repository: { url: 'https://github.com/Amet13/overfull', source: 'github' },
      packages: [
        {
          registryType: 'oci',
          identifier: `${IMAGE}:${version}-check`,
          transport: { type: 'stdio' },
          runtimeHint: 'docker',
          runtimeArguments: [
            {
              type: 'named',
              name: '--mount',
              value: 'type=bind,src={project_dir},dst=/work',
              description: 'The LaTeX project folder, mounted where the server works',
              isRequired: true,
              variables: {
                project_dir: {
                  description: 'The LaTeX project folder (the one with overfull.yml)',
                  format: 'filepath',
                  isRequired: true,
                },
              },
            },
          ],
          packageArguments: [
            { type: 'positional', valueHint: 'program', value: 'overfull' },
            { type: 'positional', valueHint: 'command', value: 'mcp' },
          ],
        },
      ],
    },
    null,
    2,
  )}\n`;
}

/** The repository files for one release, as path → content. */
export function repoFiles(version, sums) {
  return {
    'Formula/overfull.rb': formula(version, sums),
    'bucket/overfull.json': scoop(version, sums),
    'flake.nix': flake(version, sums),
    'server.json': serverJson(version),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({
    options: {
      version: { type: 'string' },
      sums: { type: 'string' },
      out: { type: 'string' },
      repo: { type: 'string' },
    },
  });
  if (!values.version || !values.sums || (!values.out && !values.repo)) {
    console.error(
      'Usage: node packaging/generate.mjs --version X.Y.Z --sums SHA256SUMS [--out dir] [--repo dir]',
    );
    process.exit(2);
  }
  const sums = parseSums(readFileSync(values.sums, 'utf8'));
  if (values.out) {
    writeFileSync(join(values.out, 'overfull.rb'), formula(values.version, sums));
    writeFileSync(join(values.out, 'overfull.json'), scoop(values.version, sums));
    console.log(`wrote overfull.rb and overfull.json for v${values.version} to ${values.out}`);
  }
  if (values.repo) {
    const files = repoFiles(values.version, sums);
    for (const [path, content] of Object.entries(files)) {
      const target = join(values.repo, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
    console.log(`wrote ${Object.keys(files).join(', ')} for v${values.version} to ${values.repo}`);
  }
}
